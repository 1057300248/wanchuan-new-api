package service

import (
	"context"
	"fmt"
	"strconv"
	"strings"

	"github.com/QuantumNous/new-api/model"
)

// TaskPersistenceUncertainError means the original INSERT failed to acknowledge
// and its destination-bound readback could not resolve the outcome. It changes
// neither refund eligibility nor retry policy. The private receipt is retained
// only for exact-identity reconciliation and must never be sent to clients/logs.
type TaskPersistenceUncertainError struct {
	receipt      model.BillingFinalization
	taskPublicID string
	cause        error
}

// TaskPersistenceCorrelation is safe correlation evidence, not a receipt that
// the task exists or was accepted. No upstream ID, task payload or key is here.
type TaskPersistenceCorrelation struct {
	Code        string `json:"code"`
	Persistence string `json:"persistence"`
	RequestID   string `json:"request_id,omitempty"`
	TaskID      string `json:"task_id,omitempty"`
}

func (e *TaskPersistenceUncertainError) Correlation() TaskPersistenceCorrelation {
	c := TaskPersistenceCorrelation{Code: "task_persistence_uncertain", Persistence: "uncertain"}
	// These are generated by the host, not copied from upstream. Bound and
	// allowlist them as well so an embedded caller cannot inject a header/log.
	for _, field := range []struct {
		value string
		max   int
		out   *string
	}{{e.receipt.RequestID, 64, &c.RequestID}, {e.taskPublicID, 191, &c.TaskID}} {
		if len(field.value) > 0 && len(field.value) <= field.max && strings.IndexFunc(field.value, func(r rune) bool {
			return r != '_' && r != '-' && !(r >= '0' && r <= '9') && !(r >= 'a' && r <= 'z') && !(r >= 'A' && r <= 'Z')
		}) == -1 {
			*field.out = field.value
		}
	}
	return c
}

func (e *TaskPersistenceUncertainError) Error() string {
	c := e.Correlation()
	return fmt.Sprintf("%s request_id=%q task_id=%q", c.Code, c.RequestID, c.TaskID)
}

// Format also protects diagnostic %#v/%+v logging of the private receipt.
func (e *TaskPersistenceUncertainError) Format(state fmt.State, verb rune) {
	message := e.Error()
	if verb == 'q' {
		message = strconv.Quote(message)
	}
	_, _ = state.Write([]byte(message))
}

func (e *TaskPersistenceUncertainError) Unwrap() error { return e.cause }

// Reconcile is read-only and caller-cancellable; it never resubmits, claims an
// owner, settles or refunds. An absent row is only not_observed, not retry-safe.
func (e *TaskPersistenceUncertainError) Reconcile(ctx context.Context) (model.BillingTaskPersistenceEvidence, error) {
	return model.InspectBillingTaskPersistence(ctx, e.receipt, e.taskPublicID)
}
